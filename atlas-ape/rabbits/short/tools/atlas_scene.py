"""Atlas performance for the whole Short → ~/shorts/orangutan/scenes/rabbits_short.json (data only, rig untouched).
Lip sync: Rhubarb Lip Sync 1.14.0 (data/rhubarb.json, run with the dialog text) → same mapping as src/engine/rhubarb.ts.
Acting cues are anchored to words (data/words.json). Export (from ~/shorts/orangutan):
  npm run export -- rabbits_short --w 1800 --h 1400
The scene stage is authored for 1080×1920 and scales with the output size (fx = W/1080, fy = H/1920, k = scale·min(fx, fy)),
so the values below put the root at (820, 1350) px with k = 1.5 in an 1800×1400 canvas: every gesture fits
(pointer +628·1.5 to the right, wave −524·1.5 to the left, hat ≈ 1250 px above the root).
"""
import json, shutil, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RIG = Path.home() / 'shorts/orangutan'
W, H = 1800, 1400
CX, CY, K = 820, 1350, 1.5
fx, fy = W / 1080, H / 1920
stage = {'x': round(CX / fx, 3), 'y': round(CY / fy, 3), 'scale': round(K / min(fx, fy), 4)}

words = json.load(open(ROOT / 'data/words.json'))
def T(i, d=0.0):
	return round(words[i]['s'] + d, 3)

MAP = {'A': 'MBP', 'B': 'E', 'C': 'E', 'D': 'AI', 'E': 'O', 'F': 'U', 'G': 'FV', 'H': 'LTH', 'X': 'rest'}
cues = json.load(open(ROOT / 'data/rhubarb.json'))['mouthCues']
vis = []
for c in cues:
	v = MAP.get(c['value'], 'rest')
	if not vis or vis[-1]['v'] != v:
		vis.append({'t': round(c['start'], 3), 'v': v})
if vis[-1]['v'] != 'rest':
	vis.append({'t': round(cues[-1]['end'], 3), 'v': 'rest'})

DUR = 62.0
tl = [
	# frame 0 = the final pose (front, smug) so the loop back from the end is seamless
	{'t': 0, 'do': 'view', 'id': 'front', 'blink': False},
	{'t': 0, 'do': 'lookAt', 'target': 'camera'},
	{'t': 0, 'do': 'emotion', 'id': 'sarcastic', 'intensity': 0.4, 'transition': 0},
	{'t': 0, 'do': 'say', 'visemes': vis, 'duration': DUR, 'audio': 'rabbits_vo.wav'},
	# HOOK: turns to the ship and points along the gangplank («Thirteen rabbits got on a ship»)
	{'t': 0.22, 'do': 'view', 'id': 'three_quarter_right'},
	{'t': 0.22, 'do': 'emotion', 'id': 'excited', 'intensity': 0.6, 'transition': 0.2},
	{'t': 0.3, 'do': 'play', 'id': 'point_stick'},
	# «Twenty-four got off.» — double take
	{'t': T(9, -0.25), 'do': 'view', 'id': 'front'},
	{'t': T(9, -0.25), 'do': 'play', 'id': 'surprise_reaction'},
	{'t': T(9, -0.2), 'do': 'emotion', 'id': 'surprised', 'intensity': 0.85, 'transition': 0.12},
	# «Turns out, rabbits can multiply.» — counts on his fingers, impressed (small, lower right, next to the classroom)
	{'t': T(12, -0.3), 'do': 'view', 'id': 'three_quarter_left'},
	{'t': T(12, -0.2), 'do': 'emotion', 'id': 'thinking', 'intensity': 0.6, 'transition': 0.15},
	{'t': T(13, -0.05), 'do': 'play', 'id': 'count_three'},
	{'t': T(16, 0.0), 'do': 'emotion', 'id': 'surprised', 'intensity': 0.7, 'transition': 0.12},
	{'t': T(17, 0.2), 'do': 'emotion', 'id': 'neutral', 'transition': 0.2},
	# KEY MOMENT «They forgot birds.» — facepalm
	{'t': T(41, -0.75), 'do': 'view', 'id': 'front'},
	{'t': T(41, -0.75), 'do': 'emotion', 'id': 'sarcastic', 'intensity': 0.7, 'transition': 0.15},
	{'t': T(42, -0.4), 'do': 'play', 'id': 'facepalm'},
	{'t': T(48, 0.0), 'do': 'emotion', 'id': 'neutral', 'transition': 0.2},
	# FINAL: smug on the score, shrug on «Australia zero», thinking → skeptical, wink on «Probably.»
	{'t': T(102, -0.45), 'do': 'view', 'id': 'front'},
	{'t': T(102, -0.45), 'do': 'emotion', 'id': 'happy', 'intensity': 0.5, 'transition': 0.15},
	{'t': T(105, -0.1), 'do': 'play', 'id': 'nod'},
	{'t': T(108, -0.25), 'do': 'play', 'id': 'shrug'},
	{'t': T(108, -0.2), 'do': 'emotion', 'id': 'sarcastic', 'intensity': 0.8, 'transition': 0.15},
	{'t': T(110, -0.1), 'do': 'view', 'id': 'three_quarter_right'},
	{'t': T(110, -0.1), 'do': 'emotion', 'id': 'thinking', 'intensity': 0.7, 'transition': 0.2},
	{'t': T(117, -0.15), 'do': 'emotion', 'id': 'skeptical', 'intensity': 0.9, 'transition': 0.12},
	{'t': T(118, -0.35), 'do': 'view', 'id': 'front'},
	{'t': T(118, -0.05), 'do': 'play', 'id': 'wink'},
	{'t': T(118, 0.75), 'do': 'emotion', 'id': 'sarcastic', 'intensity': 0.4, 'transition': 0.25},
]
scene = {
	'id': 'rabbits_short',
	'description': ('«Australia vs Rabbits» Short (The Atlas Ape): Atlas narrates the whole 62.0 s voice-over (ElevenLabs «Silas», '
	                'vo_silas_v4_gen2) — ACCURATE lip sync from Rhubarb Lip Sync 1.14.0 run on the real VO with the dialog text; '
	                'acting cues anchored to whisper word times. Generated by atlas-ape/rabbits/short/tools/atlas_scene.py.'),
	'duration': DUR, 'fps': 30, 'stage': stage,
	'timeline': sorted(tl, key=lambda s: s['t']),
}
(RIG / 'scenes/rabbits_short.json').write_text(json.dumps(scene, indent=1))
audio = RIG / 'assets/audio/rabbits_vo.wav'
if not audio.exists():
	subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(ROOT.parent / 'vo_silas_v4_gen2_mult.mp3'), '-ar', '48000', '-ac', '1', str(audio)], check=True)
print('scene →', RIG / 'scenes/rabbits_short.json', len(vis), 'viseme keys, stage', stage)
