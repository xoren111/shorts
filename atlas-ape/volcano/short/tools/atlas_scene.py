"""Atlas performance for the whole Short → ~/shorts/orangutan/scenes/volcano_short.json (data only, rig untouched).
Lip sync: Rhubarb Lip Sync 1.14.0 (data/rhubarb.json, run with the dialog text) → same mapping as src/engine/rhubarb.ts.
Acting cues are anchored to words (data/words.json). Export (from ~/shorts/orangutan):
  npm run export -- volcano_short --w 1800 --h 1400
The scene stage is authored for 1080×1920 and scales with the output size (fx = W/1080, fy = H/1920, k = scale·min(fx, fy)),
so the values below put the root at (820, 1350) px with k = 1.5 in an 1800×1400 canvas: every gesture fits
(pointer +628·1.5 to the right, wave −524·1.5 to the left, hat ≈ 1250 px above the root).
"""
import json, shutil, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RIG = Path.home() / 'shorts/orangutan'
W, H = 1800, 1400
CX, CY, K = 820, 1350, 1.5
fx, fy = W / 1080, H / 1920
stage = {'x': round(CX / fx, 3), 'y': round(CY / fy, 3), 'scale': round(K / min(fx, fy), 4)}

words = json.load(open(ROOT / 'data/words.json'))
def T(i, d=0.0):
	return round(words[i]['s'] + d, 3)

MAP = {'A': 'MBP', 'B': 'E', 'C': 'E', 'D': 'AI', 'E': 'O', 'F': 'U', 'G': 'FV', 'H': 'LTH', 'X': 'rest'}
cues = json.load(open(ROOT / 'data/rhubarb.json'))['mouthCues']
vis = []
for c in cues:
	v = MAP.get(c['value'], 'rest')
	if not vis or vis[-1]['v'] != v:
		vis.append({'t': round(c['start'], 3), 'v': v})
if vis[-1]['v'] != 'rest':
	vis.append({'t': round(cues[-1]['end'], 3), 'v': 'rest'})

