"""data/flows.json → src/data/geo.ts (anchors for cameras, pins, props; the flows themselves are in lava.png)"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
F = json.load(open(ROOT / 'data/flows.json'))
M, E, H = F['mauna_loa_1935'], F['etna_1991_93'], F['eldfell_1973']
ll = lambda p: f'[{p[0]}, {p[1]}] as LL'
lls = lambda ps: '[' + ', '.join(f'[{p[0]}, {p[1]}]' for p in ps) + '] as LL[]'
b = M['bomb_targets']
third = [(b[0][0] + b[1][0]) / 2, (b[0][1] + b[1][1]) / 2 + 0.0015]
ent = H['harbor_entrance']
ts = f'''// GENERATED by tools/geo_ts.py from data/flows.json — do not edit by hand.
// Anchors (lat, lon) from published maps (USGS SIM 2932-A / OF 2007-1089; OSM «Lave del 1992» + Barberi et al. 1993;
// USGS OF 97-724 + «Man Against Volcano»). The flows themselves are baked into public/terrain/<region>/lava.png.
export type LL = [number, number];

export const ML_PATH: LL[] = {lls(M['paths']['main'])};

/** point at fraction k of a polyline (by length) */
export const along = (pts: LL[], k: number): LL => {{
	const seg: number[] = [];
	let tot = 0;
	for (let i = 0; i < pts.length - 1; i++) {{
		const d = Math.hypot(pts[i + 1][0] - pts[i][0], (pts[i + 1][1] - pts[i][1]) * Math.cos((pts[i][0] * Math.PI) / 180));
		seg.push(d);
		tot += d;
	}}
	let x = Math.max(0, Math.min(1, k)) * tot;
	for (let i = 0; i < seg.length; i++) {{
		if (x <= seg[i] || i === seg.length - 1) {{
			const u = seg[i] > 0 ? Math.min(1, x / seg[i]) : 0;
			return [pts[i][0] + (pts[i + 1][0] - pts[i][0]) * u, pts[i][1] + (pts[i + 1][1] - pts[i][1]) * u];
		}}
		x -= seg[i];
	}}
	return pts[pts.length - 1];
}};

export const GEO = {{
	hawaii: {{
		summit: {ll(M['places']['Mauna Loa summit'])},
		hilo: {ll(M['places']['Hilo'])},
		vent: {ll(M['vent'])},
		pond: {ll(M['places']['Puuhuluhulu (kipuka, pond site)'])},
		front: {ll(M['front_stop'])},
		// two documented target areas within 2 km of the vent (+ a third drop between them for the three-plane raid)
		bombs: {lls(b + [third])},
	}},
	etna: {{
		summit: {ll(E['places']['Etna summit'])},
		vent: {ll(E['vent'])},
		tube: {ll(E['tube_blast'])},
		tubePath: {lls(E['paths']['original'][:4])},
		diverted: {lls(E['paths']['diverted'])},
		original: {lls(E['paths']['original'])},
		mid: {ll(E['places']['Monte Zoccolaro'])},
		both: [{(E['vent'][0] + E['tube_blast'][0]) / 2 - 0.002}, {(E['vent'][1] + E['tube_blast'][1]) / 2 + 0.01}] as LL,
		barrier: {lls(E['barrier'])},
		town: {ll(E['places']['Zafferana Etnea'])},
		front: {ll(E['front_closest'])},
	}},
	heimaey: {{
		town: {ll(H['places']['Heimaey town'])},
		crater: {ll(H['crater'])},
		fissure: {lls(H['fissure'])},
		harborMouth: {lls(ent)},
		front: {ll(H['front_stop'])},
		frontOpp: {ll(ent[1])},
		lobeMid: {ll(H['paths']['harbor_lobe'][3])},
		harborInner: [63.4454, -20.272] as LL,
		pumping: {lls(H['pumping'][:3])},
		heimaklettur: {ll(H['places']['Heimaklettur'])},
	}},
}};
'''
(ROOT / 'src/data/geo.ts').write_text(ts)
print('geo.ts written')
