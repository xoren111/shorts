"""Atlas performance for the whole Short → ~/shorts/orangutan/scenes/pw_short.json (data only, rig untouched).
Lip sync: Rhubarb Lip Sync 1.14.0 (data/rhubarb.json, run with the dialog text) → same mapping as src/engine/rhubarb.ts.
Acting cues are anchored to words (data/words.json). Export (from ~/shorts/orangutan):
  npm run export -- pw_short --w 1800 --h 1400
The scene stage is authored for 1080×1920 and scales with the output size (fx = W/1080, fy = H/1920, k = scale·min(fx, fy)),
so the values below put the root at (820, 1350) px with k = 1.5 in an 1800×1400 canvas: every gesture fits
(pointer +628·1.5 to the right, wave −524·1.5 to the left, hat ≈ 1250 px above the root).
"""
import json, shutil, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RIG = Path.home() / 'shorts/orangutan'
W, H = 1800, 1400
CX, CY, K = 820, 1350, 1.5
fx, fy = W / 1080, H / 1920
stage = {'x': round(CX / fx, 3), 'y': round(CY / fy, 3), 'scale': round(K / min(fx, fy), 4)}

words = json.load(open(ROOT / 'data/words.json'))
def T(i, d=0.0):
	return round(words[i]['s'] + d, 3)

MAP = {'A': 'MBP', 'B': 'E', 'C': 'E', 'D': 'AI', 'E': 'O', 'F': 'U', 'G': 'FV', 'H': 'LTH', 'X': 'rest'}
cues = json.load(open(ROOT / 'data/rhubarb.json'))['mouthCues']
vis = []
for c in cues:
	v = MAP.get(c['value'], 'rest')
	if not vis or vis[-1]['v'] != v:
		vis.append({'t': round(c['start'], 3), 'v': v})
if vis[-1]['v'] != 'rest':
	vis.append({'t': round(cues[-1]['end'], 3), 'v': 'rest'})

DUR = 43.85
# «The Pig War»: Atlas only in the finale (38.24 →), the narrator's voice → lip sync over the whole VO (shown only there)
tl = [
	{'t': 0, 'do': 'view', 'id': 'front', 'blink': False},
	{'t': 0, 'do': 'lookAt', 'target': 'camera'},
	{'t': 0, 'do': 'emotion', 'id': 'neutral', 'intensity': 0.5, 'transition': 0},
	{'t': 0, 'do': 'say', 'visemes': vis, 'duration': DUR, 'audio': 'pw_vo.wav'},
	# «Total casualties:» — solemn, looks up at the angel on its cloud
	{'t': T(91, -0.3), 'do': 'emotion', 'id': 'sad', 'intensity': 0.55, 'transition': 0.15},
	{'t': T(91, 0.1), 'do': 'play', 'id': 'look_up'},
	# «one pig.» — can't hold it: laughs
	{'t': T(94, 0.05), 'do': 'emotion', 'id': 'laughing', 'intensity': 0.9, 'transition': 0.1},
	{'t': T(94, 0.05), 'do': 'play', 'id': 'laugh'},
	# «Team farmer, or team pig?» — turns to the poll, thinking
	{'t': T(95, -0.15), 'do': 'view', 'id': 'three_quarter_right'},
	{'t': T(95, -0.15), 'do': 'emotion', 'id': 'thinking', 'intensity': 0.75, 'transition': 0.2},
	{'t': T(95, 0.0), 'do': 'play', 'id': 'thinking'},
	{'t': T(99, 0.45), 'do': 'view', 'id': 'front'},
	{'t': T(99, 0.45), 'do': 'emotion', 'id': 'sarcastic', 'intensity': 0.6, 'transition': 0.2},
]
scene = {
	'id': 'pw_short',
	'description': ('«The Pig War» Short (The Atlas Ape): Atlas over the whole 43.85 s voice-over (ElevenLabs «Silas», Eleven v4, '
	                'vo_silas_v4_gen1_tight) — lip sync from Rhubarb Lip Sync 1.14.0 run on the real VO with the dialog text; '
	                'acting cues anchored to whisper word times. Generated by atlas-ape/pig-war/short/tools/atlas_scene.py.'),
	'duration': DUR, 'fps': 30, 'stage': stage,
	'timeline': sorted(tl, key=lambda s: s['t']),
}
(RIG / 'scenes/pw_short.json').write_text(json.dumps(scene, indent=1))
audio = RIG / 'assets/audio/pw_vo.wav'
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(ROOT.parent / 'vo_silas_v4_gen1_tight.wav'), '-ar', '48000', '-ac', '1', str(audio)], check=True)
print('scene →', RIG / 'scenes/pw_short.json', len(vis), 'viseme keys, stage', stage)
