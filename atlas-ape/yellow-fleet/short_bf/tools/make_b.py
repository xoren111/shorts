"""Variant B with the FRIEND's voice («The Yellow Fleet», 21.10, the channel audit notes): the v8 cut minus two lines, in the pauses
  «And the canal became the front line.»    words 28–34, VO 9.610–11.800
  «In the end, just two could still sail.»  words 68–75, VO 24.640–27.025
→ data/vo_b.wav (10 ms crossfades), data/words.json (cut words flagged, later words shifted), src/data/shots.ts
(front + twosail gone; sink holds until the lake, podium until the route map).
  python3 tools/make_b.py      (reads the v8 data from ../short)"""
import json, wave
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
V8 = ROOT.parent / 'short'
VO = ROOT.parent / 'short_f/data/vo_f.wav'   # friend's voice, already on the v8 clock (short_f/tools/fit_friend.py)
CUTS = [(9.650, 11.750, range(28, 35)), (24.660, 26.955, range(68, 76))]   # friend's take: ~0.24 s pause left at each cut (0.15 s sounded rushed)
XF = 0.010

w = wave.open(str(VO))
sr, ch, sw = w.getframerate(), w.getnchannels(), w.getsampwidth()
x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32)
keep, a = [], 0.0
for c0, c1, _ in CUTS:
	keep.append((a, c0))
	a = c1
keep.append((a, len(x) / sr))
n = int(XF * sr)
out = x[int(keep[0][0] * sr): int(keep[0][1] * sr)].copy()
for k0, k1 in keep[1:]:
	seg = x[int(k0 * sr): int(k1 * sr)].copy()
	ramp = np.linspace(0, 1, n)
	out[-n:] = out[-n:] * (1 - ramp) + seg[:n] * ramp
	out = np.concatenate([out, seg[n:]])
with wave.open(str(ROOT / 'data/vo_b.wav'), 'wb') as o:
	o.setnchannels(ch)
	o.setsampwidth(sw)
	o.setframerate(sr)
	o.writeframes(np.clip(out, -32768, 32767).astype(np.int16).tobytes())
print(f'vo_b.wav {len(out) / sr:.3f} s (v8 {len(x) / sr:.3f} s)')


def shift(t):
	"""v8 VO time → B time (only for times outside the removed spans)"""
	d = 0.0
	for c0, c1, _ in CUTS:
		if t >= c1 - 1e-6:
			d += c1 - c0
	return round(t - d, 3)


def shift_lead(t):
	"""like shift(), but a shot that started inside a removed span keeps its lead (J-cut) before the cut point"""
	for c0, c1, _ in CUTS:
		if c0 < t < c1:
			return round(shift(c1) - (c1 - t), 3)
	return shift(t)


cut_words = {i for _, _, r in CUTS for i in r}
words = json.load(open(ROOT.parent / 'short_f/data/words.json'))   # friend's word times (v8 clock)
for i, wd in enumerate(words):
	if i in cut_words:
		wd['cut'] = True
	else:
		wd['s'], wd['e'] = shift(wd['s']), shift(wd['e'])
json.dump(words, open(ROOT / 'data/words.json', 'w'), indent=1)

DCUT = sum(c1 - c0 for c0, c1, _ in CUTS)
S8 = {'then': (0.0, 3.26), 'later': (3.26, 5.14), 'war': (5.14, 7.14), 'sink': (7.14, 8.989), 'lake': (11.57, 13.66), 'storm': (13.66, 16.78),
      'friends': (16.78, 19.95), 'football': (19.95, 21.06), 'stamps': (21.06, 22.22), 'race': (22.22, 23.58), 'dive': (22.22, 23.58),
      'sprint': (22.22, 23.58), 'podium': (23.58, 24.378), 'hamburg': (26.75, 29.86), 'hold': (29.86, 36.7)}
R = {k: shift_lead(a) for k, (a, b) in S8.items()}                 # where each Blender sequence starts (frame 1)
S = {k: [shift_lead(a), shift_lead(b) if k != 'hold' else round(36.7 - DCUT, 3)] for k, (a, b) in S8.items()}
S['sink'][1] = S['lake'][0]                                   # the paper cutaway holds until the lake dissolves in
S['hamburg'][0] = round(shift(24.545) - 0.05, 3)             # route map right as «won.» ends (waveform; whisper says 24.389)
S['podium'][1] = S['hamburg'][0]
END = round(36.7 - DCUT, 3)
lines = ['// GENERATED by tools/make_b.py (variant B: v8 minus «front line» + «just two could still sail»). Absolute seconds of data/vo_b.wav.',
         'export const XF = 0.4;', f'export const END = {END};', f'/** v8 → B time shift of everything after both cuts (Atlas frames are indexed on the v8 clock) */',
         f'export const DCUT = {DCUT:.3f};', 'export const S = {']
lines += [f'\t{k}: [{a}, {b}] as const,' for k, (a, b) in S.items()]
lines += ['};', '/** start of each Blender frame sequence (frame 1) — equals S[k][0] unless the window was trimmed */', 'export const R: Record<ShotKey, number> = {']
lines += [f'\t{k}: {v},' for k, v in R.items()]
lines += ['};', 'export type ShotKey = keyof typeof S;', '']
(ROOT / 'src/data/shots.ts').write_text('\n'.join(lines))
print(f'END {END}  DCUT {DCUT:.3f}')
for k, (a, b) in S.items():
	print(f'  {k:9s} {a:7.3f} {b:7.3f}  (seq from {R[k]})')
